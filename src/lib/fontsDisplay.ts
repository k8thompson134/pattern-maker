// Hand-drawn capitals for the display fonts, written as '#' (stitch) and '.' (blank).
type Art = Record<string, string[]>

export function fromArt(art: Art): Record<string, string[]> {
  return Object.fromEntries(Object.entries(art).map(([ch, rows]) => [ch, rows.map((r) => r.replace(/#/g, '1').replace(/\./g, '0'))]))
}

